// Builds the Pokémon Center healing machine's pictures from pret/pokefirered:
//
//   node tools/build-field-effects.js <path to pokefirered>   (or set POKEFIRERED)
//
// Writes data/field-effects.js: window.FIELD_EFFECTS = { palette, ball, monitor },
// FireRed's graphics/field_effects/pics/pokeball_glow.png (an 8x8 Poké Ball) and
// pokemoncenter_monitor.png (four 32x16 frames of the machine's screen, one
// under the other) as colour numbers (one hex digit a pixel, 0 = clear), and
// the palette both use (sprite palette 4103, the Poké Ball's). The colour
// numbers stay so the overworld can flash colours 2, 3, 5, 6 and 8 the way
// FireRed does while it heals (src/field_effect.c).
"use strict";

const fs = require("fs");
const path = require("path");
const { readPng } = require("./lib/png");

const pret = process.argv[2] || process.env.POKEFIRERED;
const pics = pret && path.join(pret, "graphics/field_effects/pics");
if (!pics || !fs.existsSync(path.join(pics, "pokeball_glow.png"))) {
  console.error("Usage: node tools/build-field-effects.js <path to pret/pokefirered>  (needs graphics/field_effects/ checked out)");
  process.exit(1);
}
const root = path.join(__dirname, "..");

const ball = readPng(path.join(pics, "pokeball_glow.png"));
const monitor = readPng(path.join(pics, "pokemoncenter_monitor.png"));
const hex = (img) => Array.from(img.px, (v) => v.toString(16)).join("");
const data = {
  palette: ball.palette.slice(0, 16),
  ball: { width: ball.width, height: ball.height, px: hex(ball) },
  monitor: { width: monitor.width, height: monitor.height / 4, frames: 4, px: hex(monitor) }
};
fs.writeFileSync(path.join(root, "data/field-effects.js"),
  "// Auto-generated by tools/build-field-effects.js from pret/pokefirered. Do not edit by hand.\n" +
  "window.FIELD_EFFECTS = " + JSON.stringify(data) + ";\n");
console.log("wrote data/field-effects.js");
