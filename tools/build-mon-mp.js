// The Ultimax battles' MP for the first 386 Pokémon (Bulbasaur to Deoxys), as their base stats have it: out of
// the Pokémon realm a Pokémon's moves cost MP, as everyone else's skills do, and Pokémon have no MP of their own.
// Its base MP is its Special Attack's 45%, its Special Defense's 30% and its HP's 25% (a caster's more, a bruiser's
// less), and its MP at a level is Ultimax's own formula (engine/battle.js monMp).
//
//   node tools/build-mon-mp.js   -> data/mon-mp.js (window.MON_MP: { species: base MP })
"use strict";
const fs = require("fs");
const path = require("path");
global.window = global;
require("../data/dex.js");
const out = {};
for (const [name, d] of Object.entries(window.DEX)) {
  if (!(d.id >= 1 && d.id <= 386) || out[name] != null) continue;
  // (each species once: its own entry, not its forms', Mega or Alolan, which keep their species' MP)
  if (/-/.test(name) && Object.values(window.DEX).some((o) => o.id === d.id && !/-/.test(Object.keys(window.DEX).find((k) => window.DEX[k] === o)))) continue;
  out[name] = Math.round(0.45 * d.spa + 0.3 * d.spd + 0.25 * d.hp);
}
const file = path.join(__dirname, "..", "data/mon-mp.js");
fs.writeFileSync(file, "// Auto-generated by tools/build-mon-mp.js. Do not edit by hand.\n// The first 386 Pokémon's base MP, for the Ultimax battles (engine/battle.js monMp).\nwindow.MON_MP = " +
  JSON.stringify(out) + ";\n");
console.log(Object.keys(out).length + " Pokémon");
