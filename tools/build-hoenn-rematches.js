// Emerald's rematch teams (src/battle_setup.c's gRematchTable: each Trainer's later parties, TRAINER_ROSE_2 to
// TRAINER_ROSE_5 and the like), which the Hoenn build (tools/build-hoenn.js) leaves out, into
// data/hoenn-rematches.js: window.WORLD_TRAINERS entries, each with its first battle's class, name, picture and
// music, and its own party (src/data/trainers.h, src/data/trainer_parties.h). ui/game.js's rematch ("Rematch?")
// battles a Hoenn Trainer as Emerald would: their first team you haven't beaten (HOENN_MATCH_CALL.teams).
//
//   node tools/build-hoenn-rematches.js <path to pret/pokeemerald>
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const EM = process.argv[2] || process.env.POKEEMERALD;
if (!EM || !fs.existsSync(path.join(EM, "src/data/trainer_parties.h"))) {
  console.error("Usage: node tools/build-hoenn-rematches.js <path to pret/pokeemerald>");
  process.exit(1);
}
const root = path.join(__dirname, "..");
global.window = global;
// (Emerald's Pokémon, moves and items are all among the first generations': this game's own lists of them.)
for (const f of ["data/dex.js", "data/moves.js", "data/items.js"]) if (fs.existsSync(path.join(root, f))) vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));
window.WORLD_MAPS = {}; window.WORLD_TRAINERS = {};
vm.runInThisContext(fs.readFileSync(path.join(root, "data/emerald-maps.js"), "utf8"));
const toID = (s) => String(s).toLowerCase().replace(/[^a-z0-9]/g, "");
const byID = (obj) => { const o = {}; for (const k of Object.keys(obj)) o[toID(k)] = k; return o; };
const dexByID = byID(window.DEX), moveByID = byID(window.MOVES), itemByID = byID(window.ITEMS);
const trainerSrc = fs.readFileSync(path.join(EM, "src/data/trainers.h"), "utf8"), partySrc = fs.readFileSync(path.join(EM, "src/data/trainer_parties.h"), "utf8");

function party(id) {
  const m = new RegExp("\\[" + id + "\\] =\\s*\\{([\\s\\S]*?)\\n    \\},").exec(trainerSrc);
  if (!m) return null;
  const name = (/NO_ITEM_DEFAULT_MOVES\((\w+)\)|NO_ITEM_CUSTOM_MOVES\((\w+)\)|ITEM_DEFAULT_MOVES\((\w+)\)|ITEM_CUSTOM_MOVES\((\w+)\)/.exec(m[1]) || []).slice(1).find(Boolean);
  const list = name && new RegExp(name + "\\[\\] = \\{([\\s\\S]*?)\\n\\};").exec(partySrc);
  if (!list) return null;
  return [...list[1].matchAll(/\{([^{}]*(?:\{[^}]*\}[^{}]*)*)\}/g)].map(([, mon]) => {
    const species = dexByID[toID(/\.species = SPECIES_(\w+)/.exec(mon)[1])];
    const moves = /\.moves = \{([^}]*)\}/.exec(mon), item = /\.heldItem = ITEM_(\w+)/.exec(mon);
    return { species, level: +/\.lvl = (\d+)/.exec(mon)[1], iv: +/\.iv = (\d+)/.exec(mon)[1],
      item: item && item[1] !== "NONE" ? itemByID[toID(item[1])] : undefined,
      moves: moves ? moves[1].split(",").map((x) => x.trim().replace(/^MOVE_/, "")).filter((x) => x && x !== "NONE").map((x) => moveByID[toID(x)]).filter(Boolean) : undefined };
  }).filter((p) => p.species);
}

const out = {};
for (const [first, tiers] of Object.entries(window.HOENN_MATCH_CALL.teams)) {
  const base = window.WORLD_TRAINERS[first];
  if (!base) continue;
  for (const key of tiers) {
    if (window.WORLD_TRAINERS[key] || out[key]) continue;
    const p = party(key.replace(/^EM_/, ""));
    if (!p || !p.length) { console.warn("no party for " + key); continue; }
    out[key] = { className: base.className, name: base.name, pic: base.pic, music: base.music, double: base.double, party: p };
  }
}
fs.writeFileSync(path.join(root, "data/hoenn-rematches.js"),
  "// Auto-generated by tools/build-hoenn-rematches.js from pret/pokeemerald. Do not edit by hand.\n" +
  "// Emerald's rematch teams (gRematchTable's later parties), for ui/game.js's Hoenn rematches.\n" +
  "Object.assign(window.WORLD_TRAINERS, " + JSON.stringify(out) + ");\n");
console.log("wrote " + Object.keys(out).length + " rematch teams to data/hoenn-rematches.js");
