// Z-Moves (Sun and Moon): the 34 Z-Moves and what each Z-Crystal does, from
// @pkmn/dex (Pokémon Showdown's data, Gen 7):
//
//   node tools/build-z-moves.js
//
// Writes data/z-moves.js: the Z-Moves added to window.MOVES (gen 7, isZ), and
// window.Z_MOVES:
//   power:   { move: its Z-Move's power } for every damaging move here
//   status:  { move: { boost } | { effect } } a status move's Z-Power bonus
//            (effect: clearnegativeboost, crit2, heal, curse, redirect,
//            healreplacement)
//   byType:  { type: its Z-Move } (Breakneck Blitz, Inferno Overdrive, ...)
//   crystals: { item: { type } | { from, move, users } } the type Z-Crystals,
//            and the species' own (Pikanium Z: Pikachu's Volt Tackle into
//            Catastropika). Not Pikashunium Z (Pikachu in a cap).
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { Dex } = require("@pkmn/dex");

const root = path.join(__dirname, "..");
global.window = global;
window.LEARNSETS_GEN6 = {};
for (const f of ["data/dex.js", "data/dex-gen7.js", "data/dex-gen8.js", "data/dex-forms.js", "data/moves.js", "data/moves-gen7.js", "data/moves-gen8.js"]) {
  vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));
}
const gen7 = Dex.forGen(7);
const itemId = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

const zMoves = {}, power = {}, status = {}, byType = {}, crystals = {};
for (const m of gen7.moves.all()) {
  if (!m.isZ || m.isZ === "pikashuniumz") continue;
  const item = gen7.items.get(m.isZ);
  const out = { power: m.basePower, acc: null, cat: m.category, type: m.type, pp: 1, priority: 0, target: m.target,
    flags: Object.assign({}, m.flags), isZ: true, gen: 7 };
  if (m.boosts) out.boosts = m.boosts;
  if (m.secondary && Object.keys(m.secondary).some((k) => k !== "chance" && (k !== "self" || Object.keys(m.secondary.self).length))) out.secondary = m.secondary;
  if (m.selfBoost) out.self = m.selfBoost;
  if (m.ignoreAbility) out.ignoreAbility = true;
  out.desc = m.desc; out.shortDesc = m.shortDesc;
  zMoves[m.name] = out;
  if (item.zMove === true) {
    byType[m.type] = m.name;
    crystals[itemId(item.name)] = { type: m.type };
  } else {
    const users = (item.itemUser || []).filter((u) => window.DEX[u]);
    crystals[itemId(item.name)] = { from: item.zMoveFrom, move: m.name, users };
  }
}
for (const name of Object.keys(window.MOVES)) {
  const m = Dex.moves.get(name);
  if (!m.exists || !m.zMove) continue;
  if (m.zMove.basePower) power[name] = m.zMove.basePower;
  else if (m.zMove.boost || m.zMove.effect) status[name] = m.zMove.boost ? { boost: m.zMove.boost } : { effect: m.zMove.effect };
}
const ser = (o) => "{\n" + Object.entries(o).map(([k, v]) => "  " + JSON.stringify(k) + ": " + JSON.stringify(v)).join(",\n") + "\n}";
fs.writeFileSync(path.join(root, "data/z-moves.js"),
  "// Auto-generated by tools/build-z-moves.js from @pkmn/dex (Gen 7). Do not edit by hand.\n" +
  "// The Z-Moves, added to window.MOVES, and what Z-Power does with each move and Z-Crystal.\n" +
  "Object.assign(window.MOVES, " + ser(zMoves) + ");\n" +
  "window.Z_MOVES = " + JSON.stringify({ power, status, byType, crystals }) + ";\n");
console.log("wrote data/z-moves.js: " + Object.keys(zMoves).length + " Z-Moves, " + Object.keys(power).length + " powers, " +
  Object.keys(status).length + " status bonuses, " + Object.keys(crystals).length + " Z-Crystals");
