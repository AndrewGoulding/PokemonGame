// Builds data/sprite-metrics.js: where each Pokémon sprite's feet are, so the
// battle screen can stand every Pokémon on its platform.
//
//   node tools/build-sprite-metrics.js [path to pokefirered]   (or set POKEFIRERED)
//
// The sprites (assets/sprites/pokemon, 96x96) leave empty rows under small
// Pokémon; `front` and `back` give that gap in pixels per file name ("25",
// "412-sandy"). `elevation` is FireRed's gEnemyMonElevation (pixels a floating
// or flying foe sits above the ground), read from
// src/data/pokemon_graphics/enemy_mon_elevation.h when a checkout is given;
// without one, the existing table in data/sprite-metrics.js is kept.
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { readPng } = require("./lib/png");

const root = path.join(__dirname, "..");
const dir = path.join(root, "assets/sprites/pokemon");
const outFile = path.join(root, "data/sprite-metrics.js");
global.window = global;
vm.runInThisContext(fs.readFileSync(path.join(root, "data/dex.js"), "utf8"));

// Empty rows below the lowest non-transparent pixel. The top-left pixel is
// the transparent colour.
function gap(file) {
  const p = readPng(file);
  const bg = p.px[0];
  for (let y = p.height - 1; y >= 0; y--) {
    for (let x = 0; x < p.width; x++) if (p.px[y * p.width + x] !== bg) return p.height - 1 - y;
  }
  return 0;
}
function gaps(folder) {
  const out = {};
  for (const f of fs.readdirSync(folder).filter((f) => f.endsWith(".png")).sort()) out[f.slice(0, -4)] = gap(path.join(folder, f));
  return out;
}

const toID = (s) => String(s).toLowerCase().replace(/[^a-z0-9]/g, "");
let elevation = {};
const pret = process.argv[2] || process.env.POKEFIRERED;
const header = pret && path.join(pret, "src/data/pokemon_graphics/enemy_mon_elevation.h");
if (header && fs.existsSync(header)) {
  const byID = {};
  for (const k of Object.keys(window.DEX)) if (window.DEX[k].id < 10000) byID[toID(k)] = k;
  for (const [, name, n] of fs.readFileSync(header, "utf8").matchAll(/\[SPECIES_(\w+)\]\s*=\s*(\d+)/g)) {
    const species = byID[toID(name)];
    if (species && +n) elevation[species] = +n;
  }
} else if (fs.existsSync(outFile)) {
  vm.runInThisContext(fs.readFileSync(outFile, "utf8"));
  elevation = window.SPRITE_METRICS.elevation;
} else {
  console.error("usage: node tools/build-sprite-metrics.js <path to pokefirered>  (for FireRed's elevation table)");
  process.exit(1);
}

const metrics = { front: gaps(dir), back: gaps(path.join(dir, "back")), elevation };
fs.writeFileSync(outFile, "// Auto-generated by tools/build-sprite-metrics.js. Do not edit by hand.\n" +
  "// front/back: empty rows under each sprite (px of 96); elevation: FireRed's floating foes (GBA px).\n" +
  "window.SPRITE_METRICS = " + JSON.stringify(metrics) + ";\n");
console.log("wrote data/sprite-metrics.js: " + Object.keys(metrics.front).length + " front, " +
  Object.keys(metrics.back).length + " back, " + Object.keys(elevation).length + " elevated");
