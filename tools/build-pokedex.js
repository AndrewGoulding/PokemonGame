// Builds the Pokédex's entries from pret/pokefirered:
//
//   node tools/build-pokedex.js <path to pokefirered>   (or set POKEFIRERED)
//
// Writes data/pokedex-text.js: window.POKEDEX_TEXT = { <National Dex number>:
// { category: "Mouse", description: "It has small electric sacs on both its\n..." } }
// for the first 386, from src/data/pokemon/pokedex_entries.h (categoryName,
// description) and FireRed's descriptions (pokedex_text_fr.h).
"use strict";

const fs = require("fs");
const path = require("path");
const { cleanText } = require("./lib/text");

const pret = process.argv[2] || process.env.POKEFIRERED;
const P = (...p) => path.join(pret || "", ...p);
if (!pret || !fs.existsSync(P("src/data/pokemon/pokedex_entries.h")) || !fs.existsSync(P("src/data/pokemon/pokedex_text_fr.h"))) {
  console.error("Usage: node tools/build-pokedex.js <path to pret/pokefirered>  (needs src/data/pokemon/pokedex_entries.h, pokedex_text_fr.h)");
  process.exit(1);
}
const root = path.join(__dirname, "..");

// gPikachuPokedexText[] = _( "..." "..." ); -> its text
const texts = {};
const textSrc = fs.readFileSync(P("src/data/pokemon/pokedex_text_fr.h"), "utf8");
for (const [, name, body] of textSrc.matchAll(/const u8 (\w+)\[\] = _\(([\s\S]*?)\);/g)) {
  texts[name] = [...body.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => m[1]).join("");
}

// The entries, in National Dex order (NATIONAL_DEX_NONE first).
const out = {};
const entries = fs.readFileSync(P("src/data/pokemon/pokedex_entries.h"), "utf8");
let n = 0;
for (const [, block] of entries.matchAll(/\[NATIONAL_DEX_\w+\]\s*=\s*\{([\s\S]*?)\n\s*\},/g)) {
  const id = n++;
  if (!id) continue;
  const category = /\.categoryName = _\("(.*?)"\)/.exec(block)[1];
  const desc = /\.description = (\w+)/.exec(block)[1];
  out[id] = {
    category: category === "DNA" ? category : category.charAt(0) + category.slice(1).toLowerCase(),
    description: cleanText(texts[desc] || "").join("\n")
  };
}
fs.writeFileSync(path.join(root, "data/pokedex-text.js"),
  "// Auto-generated by tools/build-pokedex.js from pret/pokefirered. Do not edit by hand.\n" +
  "window.POKEDEX_TEXT = " + JSON.stringify(out) + ";\n");
console.log("wrote data/pokedex-text.js: " + Object.keys(out).length + " entries");
