// Builds data/hm-learners.js: which species can use each HM beyond what
// X and Y's machine lists say (data/learnsets.js, LEARNSETS_GEN6 .tm).
// Run with: npm run build:hm-learners
//
// The game's HMs cover every region (see game/bag.js), and some were never a
// machine in Gen 6: Whirlpool, Defog and Rock Climb. A species can use an HM
// if any generation let it learn that move from a TM or HM (@pkmn/dex
// learnsets, sources like "4M"). Formes without their own learnset use their
// base species'.
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { Dex } = require("@pkmn/dex");

const root = path.join(__dirname, "..");
global.window = global;
for (const f of ["data/dex.js", "data/moves.js", "data/items.js", "data/learnsets.js"]) {
  vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));
}

const toID = (s) => String(s).toLowerCase().replace(/[^a-z0-9]/g, "");
const hmMoves = Object.keys(window.ITEMS).filter((id) => /^hm\d+$/.test(id)).sort()
  .map((id) => /^Teaches (.+?) to a compatible/.exec(window.ITEMS[id].effect)[1]);

(async () => {
  const machineMoves = {};   // species -> Set of move ids learnable by machine in some generation
  for (const species of Object.keys(window.DEX)) {
    let data = await Dex.learnsets.get(toID(species));
    if (!data || !data.learnset) {
      const base = Dex.species.get(species);
      data = base && base.exists ? await Dex.learnsets.get(toID(base.changesFrom || base.baseSpecies)) : null;
    }
    const set = new Set();
    for (const [move, sources] of Object.entries((data && data.learnset) || {})) {
      if (sources.some((s) => /^\dM$/.test(s))) set.add(move);
    }
    machineMoves[species] = set;
  }
  const out = {};
  for (const move of hmMoves) {
    const extra = Object.keys(window.DEX).filter((species) => {
      const gen6 = (window.LEARNSETS_GEN6[species] || {}).tm || [];
      return !gen6.includes(move) && machineMoves[species].has(toID(move));
    }).sort();
    if (extra.length) out[move] = extra;
  }
  const body = "// Auto-generated by tools/build-hm-learners.js. Do not edit by hand.\n" +
    "// HM moves -> species that can use them besides those in LEARNSETS_GEN6 .tm.\n" +
    "window.HM_LEARNERS = " + JSON.stringify(out, null, 1).replace(/\n /g, "\n  ") + ";\n";
  fs.writeFileSync(path.join(root, "data/hm-learners.js"), body);
  console.log("wrote data/hm-learners.js: " + Object.entries(out).map(([m, l]) => m + " +" + l.length).join(", "));
})();
