// Builds data/breeding.js from Pokémon Showdown's Gen 6 data (@pkmn/dex):
// each species' Egg Groups, the species its Eggs hatch into, and the
// incense a parent must hold for a baby Pokémon's Egg.
// Run with: npm install && node tools/build-breeding.js
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { Dex } = require("@pkmn/dex");

const root = path.join(__dirname, "..");
global.window = global;
vm.runInThisContext(fs.readFileSync(path.join(root, "data/dex.js"), "utf8"));

const gen6 = Dex.forGen(6);
const toID = (s) => String(s).toLowerCase().replace(/[^a-z0-9]/g, "");
const dexKeys = Object.keys(window.DEX);
function ourName(name) {
  if (window.DEX[name]) return name;
  const id = toID(name);
  const exact = dexKeys.find((k) => toID(k) === id);
  if (exact) return exact;
  const base = toID(gen6.species.get(name).baseSpecies || name);
  return dexKeys.find((k) => window.DEX[k].id < 10000 && toID(k).startsWith(base)) || null;
}

// Gen 6's incense babies: without the incense, an Egg is the next stage up.
const INCENSE = {
  Azurill: "sea-incense", Wynaut: "lax-incense", Budew: "rose-incense", Chingling: "pure-incense",
  Bonsly: "rock-incense", "Mime Jr.": "odd-incense", Happiny: "luck-incense", Munchlax: "full-incense",
  Mantyke: "wave-incense"
};

const groups = {}, hatches = {};
for (const key of dexKeys) {
  const s = gen6.species.get(key);
  if (!s || !s.exists) continue;
  groups[key] = s.eggGroups.slice();
  // Down the evolution line to its first stage (stopping above an incense baby).
  let base = s;
  while (base.prevo) {
    const prev = gen6.species.get(base.prevo);
    if (INCENSE[prev.name] && base.name !== prev.name) { hatches[key + "|incense"] = ourName(prev.name); break; }
    base = prev;
  }
  // (A forme hatches as its species: Rotom-Wash's Eggs are Rotom.)
  if (base.forme && base.baseSpecies !== base.name) base = gen6.species.get(base.baseSpecies);
  hatches[key] = ourName(base.name);
}
const incense = {};
for (const [k, v] of Object.entries(hatches)) {
  if (!k.endsWith("|incense")) continue;
  incense[k.slice(0, -8)] = { baby: v, item: INCENSE[Object.keys(INCENSE).find((b) => ourName(b) === v)] };
  delete hatches[k];
}

const out = "// Auto-generated by tools/build-breeding.js from @pkmn/dex (Gen 6). Do not edit by hand.\n" +
  "// GROUPS: species -> Egg Groups. HATCHES: species -> what its Eggs hatch into.\n" +
  "// INCENSE: species -> { baby, item }: with `item` held by a parent, the Egg is `baby` instead.\n" +
  "window.BREEDING = " + JSON.stringify({ GROUPS: groups, HATCHES: hatches, INCENSE: incense }) + ";\n";
fs.writeFileSync(path.join(root, "data/breeding.js"), out);
console.log("wrote data/breeding.js: " + Object.keys(groups).length + " species");
