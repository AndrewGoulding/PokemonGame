// The battle formes of Pokémon already in the game that the generation
// imports left out, from @pkmn/dex (Pokémon Showdown's data) and PokeAPI's
// CSVs (IDs, Exp., height, weight, the sprites' file names):
//
//   node tools/build-extra-forms.js <folder with PokeAPI's data/v2/csv/*.csv> [<pokeemerald-expansion>]
//   (pokemon, pokemon_forms); it leaves extra-forms-sprites.json there for
//   tools/fetch-gen7-sprites.js. PokeAPI has no Mega Zygarde: with the
//   expansion's path it draws one from graphics/pokemon/zygarde/mega (its
//   64x64 front and back, normal and shiny), scaled 1.5x to the others' 96x96.
//
// Writes data/dex-forms.js: window.DEX's new entries, and LEARNSETS_GEN6 for
// each pointing at its species' own (the debug menu can make any of them):
//   Mega Zygarde (Legends: Z-A; Zygardite, from the Complete Forme),
//   Ultra Necrozma (Ultranecrozium Z, from Dusk Mane or Dawn Wings),
//   Dialga's and Palkia's Origin Formes (Adamant Crystal, Lustrous Globe),
//   Eternamax Eternatus, and the 34 Gigantamax formes.
// And ALCREMIE_FORMS: Alcremie's 63 looks (9 creams × 7 Sweets), sprites
// named 869-<cream>-<sweet>.png, the vanilla cream with a Strawberry Sweet
// being Alcremie's own.
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { Dex } = require("@pkmn/dex");
const { readPng, writePng, readPal } = require("./lib/png");

const csvDir = process.argv[2];
if (!csvDir || !fs.existsSync(path.join(csvDir, "pokemon.csv"))) {
  console.error("Usage: node tools/build-extra-forms.js <PokeAPI csv folder>");
  process.exit(1);
}
const root = path.join(__dirname, "..");
global.window = global;
for (const f of ["data/dex.js", "data/dex-gen7.js", "data/dex-gen8.js"]) vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));

function csv(name) {
  const [head, ...rows] = fs.readFileSync(path.join(csvDir, name + ".csv"), "utf8").trim().split(/\r?\n/).map((l) => l.split(","));
  return rows.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}
const pokemon = csv("pokemon"), forms = csv("pokemon_forms");
const pokemonBy = Object.fromEntries(pokemon.map((p) => [p.identifier, p]));

const gen7 = Dex.forGen(7), gen8 = Dex.forGen(8), gen9 = Dex.forGen(9);
// [our name, @pkmn/dex generation, PokeAPI identifier]
const LIST = [
  ["Zygarde-Mega", gen9, "zygarde-mega"],
  ["Necrozma-Ultra", gen7, "necrozma-ultra"],
  ["Dialga-Origin", gen9, "dialga-origin"],
  ["Palkia-Origin", gen9, "palkia-origin"],
  ["Eternatus-Eternamax", gen8, "eternatus-eternamax"]
];
const GMAX_API = { "Toxtricity-Gmax": "toxtricity-amped-gmax", "Urshifu-Gmax": "urshifu-single-strike-gmax" };
for (const s of gen8.species.all()) {
  if (s.isNonstandard === "Gigantamax") LIST.push([s.name, gen8, GMAX_API[s.name] || s.name.toLowerCase()]);
}

const dexOut = {}, base = {}, sprites = {};
for (const [name, dex, apiName] of LIST) {
  const s = dex.species.get(name);
  const api = pokemonBy[apiName];
  if (!s.exists || !api) throw new Error("No data for " + name);
  const from = s.changesFrom || s.baseSpecies;
  const own = window.DEX[from];
  if (!own) throw new Error("No base species for " + name);
  const a = s.abilities;
  const entry = Object.assign({}, own, {
    id: +api.id, types: s.types.slice(), abilities: [a[0], a[1]].filter(Boolean),
    hp: s.baseStats.hp, atk: s.baseStats.atk, def: s.baseStats.def, spa: s.baseStats.spa, spd: s.baseStats.spd, spe: s.baseStats.spe,
    baseExp: +api.base_experience || own.baseExp, height: +api.height / 10, weight: +api.weight / 10
  });
  delete entry.hiddenAbility;
  if (a.H) entry.hiddenAbility = a.H;
  dexOut[name] = entry;
  base[name] = from;
  sprites[entry.id] = String(api.id);
}

// Alcremie's looks: PokeAPI's forms "<cream>-<sweet>".
const alcremie = forms.filter((f) => f.pokemon_id === "869" && f.form_identifier).map((f) => f.form_identifier);
for (const f of alcremie) if (f !== "vanilla-cream-strawberry-sweet") sprites["869-" + f] = "869-" + f;

const ser = (o) => "{\n" + Object.entries(o).map(([k, v]) => "  " + JSON.stringify(k) + ": " + JSON.stringify(v)).join(",\n") + "\n}";
fs.writeFileSync(path.join(root, "data/dex-forms.js"),
  "// Auto-generated by tools/build-extra-forms.js from @pkmn/dex and PokeAPI. Do not edit by hand.\n" +
  "// Battle formes of Pokémon already in the game, added to window.DEX, with their species' learnsets.\n" +
  "Object.assign(window.DEX, " + ser(dexOut) + ");\n" +
  "for (const [form, base] of Object.entries(" + JSON.stringify(base) + ")) window.LEARNSETS_GEN6[form] = window.LEARNSETS_GEN6[base];\n" +
  "// Alcremie's looks (Party.form): \"<cream>-<sweet>\".\n" +
  "window.ALCREMIE_FORMS = " + JSON.stringify(alcremie) + ";\n");
fs.writeFileSync(path.join(csvDir, "extra-forms-sprites.json"), JSON.stringify(sprites));
const X = process.argv[3];
if (X) {
  const dir = path.join(X, "graphics/pokemon/zygarde/mega"), out = path.join(root, "assets/sprites/pokemon");
  for (const [pic, sub] of [["front", ""], ["back", "back/"]]) {
    for (const [pal, shiny] of [["normal", ""], ["shiny", "shiny/"]]) {
      const img = readPng(path.join(dir, pic + ".png")), colours = readPal(path.join(dir, pal + ".pal"));
      const rgba = new Uint8ClampedArray(96 * 96 * 4);
      for (let y = 0; y < 96; y++) for (let x = 0; x < 96; x++) {
        const v = img.px[Math.floor(y / 1.5) * img.width + Math.floor(x / 1.5)] & 15;
        if (v) rgba.set([...colours[v], 255], (y * 96 + x) * 4);
      }
      writePng(path.join(out, sub + shiny + dexOut["Zygarde-Mega"].id + ".png"), 96, 96, rgba);
    }
  }
}
console.log("wrote data/dex-forms.js: " + Object.keys(dexOut).length + " formes, " + alcremie.length + " Alcremie looks");
