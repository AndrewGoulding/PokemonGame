// Builds data/machine-learners.js: which species can use each TM or HM beyond
// what X and Y's machine lists say (data/learnsets.js, LEARNSETS_GEN6 .tm).
// Run with: npm run build:machine-learners
//
// Some of the game's machines were never a machine in Gen 6: the HMs that
// cover every region (Whirlpool, Defog, Rock Climb; see game/bag.js) and
// TM100 Bullet Seed (FireRed's TM09). A species can use one if any generation
// let it learn that move from a TM or HM (@pkmn/dex learnsets, sources like
// "4M"). Formes without their own learnset use their base species'.
//
// GAME_EXTRA adds species this game lets use a machine besides (Fly for
// Butterfree, Beedrill, Gyarados and Venomoth).
//
// Also window.TUTOR_LEARNERS: who the game's move tutors (FireRed's) can teach,
// since Gen 6 had no tutor for most of their moves (Mega Punch, Mega Kick,
// Seismic Toss, Dream Eater): any species a tutor taught in some generation
// (sources like "3T"), besides those Gen 6's learnsets already allow.
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { Dex } = require("@pkmn/dex");

const root = path.join(__dirname, "..");
global.window = global;
for (const f of ["data/dex.js", "data/moves.js", "data/items.js", "data/learnsets.js"]) {
  vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));
}

const toID = (s) => String(s).toLowerCase().replace(/[^a-z0-9]/g, "");
// The HMs, and the TMs whose move X and Y never had a machine for (Bullet Seed).
const gen6Machine = new Set();
for (const l of Object.values(window.LEARNSETS_GEN6)) for (const m of l.tm || []) gen6Machine.add(m);
const moveOf = (id) => /^Teaches (.+?) to a compatible/.exec(window.ITEMS[id].effect)[1];
const machineList = Object.keys(window.ITEMS).filter((id) => /^hm\d+$/.test(id) || (/^tm\d+$/.test(id) && !gen6Machine.has(moveOf(id))))
  .sort().map(moveOf);
// Generation 7's, 8's and 9's Pokémon (tools/build-gen7.js, build-gen8.js, build-gen9.js) get
// every machine they could use in some generation, beyond their own games'.
for (const f of ["data/dex-gen7.js", "data/moves-gen7.js", "data/learnsets-gen7.js", "data/dex-gen8.js", "data/moves-gen8.js", "data/learnsets-gen8.js",
  "data/moves-gen9.js", "data/learnsets-gen9.js", "data/dex-gen9.js"]) {
  vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));
}
const allMachines = Object.keys(window.ITEMS).filter((id) => /^(tm|hm)\d+$/.test(id)).sort().map(moveOf);
const SHOWDOWN_NAME = { Minior: "Minior-Meteor", "Minior-Core": "Minior" };

// This game's own additions: species that can use a machine no game let them.
const GAME_EXTRA = {
  "Fly": ["Butterfree", "Beedrill", "Gyarados", "Venomoth"]   // HM02, for the bug and Gyarados lines
};

// FireRed's move tutors (src/data/pokemon/tutor_learnsets.h).
const TUTOR_MOVES = ["Mega Punch", "Swords Dance", "Mega Kick", "Body Slam", "Double-Edge", "Counter", "Seismic Toss",
  "Mimic", "Metronome", "Soft-Boiled", "Dream Eater", "Thunder Wave", "Explosion", "Rock Slide", "Substitute"];

(async () => {
  const machineMoves = {};   // species -> Set of move ids learnable by machine in some generation
  const tutorMoves = {};     // species -> Set of move ids a tutor taught it in some generation
  for (const species of Object.keys(window.DEX)) {
    let data = await Dex.learnsets.get(toID(SHOWDOWN_NAME[species] || species));
    if (!data || !data.learnset) {
      const base = Dex.species.get(SHOWDOWN_NAME[species] || species);
      data = base && base.exists ? await Dex.learnsets.get(toID(base.changesFrom || base.baseSpecies)) : null;
    }
    const set = new Set(), tutor = new Set();
    for (const [move, sources] of Object.entries((data && data.learnset) || {})) {
      if (sources.some((s) => /^\dM$/.test(s))) set.add(move);
      if (sources.some((s) => /^\dT$/.test(s))) tutor.add(move);
    }
    machineMoves[species] = set;
    tutorMoves[species] = tutor;
  }
  const out = {};
  for (const move of allMachines) {
    const extra = Object.keys(window.DEX).filter((species) => {
      if (!machineList.includes(move) && !(window.DEX[species].gen >= 7)) return false;
      const gen6 = (window.LEARNSETS_GEN6[species] || {}).tm || [];
      return !gen6.includes(move) && (machineMoves[species].has(toID(move)) || (GAME_EXTRA[move] || []).includes(species));
    }).sort();
    if (extra.length) out[move] = extra;
  }
  const tutors = {};
  for (const move of TUTOR_MOVES) {
    tutors[move] = Object.keys(window.DEX).filter((species) => {
      const g = window.LEARNSETS_GEN6[species] || {};
      const gen6 = [].concat(g.tm || [], g.tutor || [], (g.levelup || []).map((l) => l[1]));
      return !gen6.includes(move) && tutorMoves[species].has(toID(move));
    }).sort();
  }
  const body = "// Auto-generated by tools/build-machine-learners.js. Do not edit by hand.\n" +
    "// Machine moves -> species that can use them besides those in LEARNSETS_GEN6 .tm.\n" +
    "window.MACHINE_LEARNERS = " + JSON.stringify(out, null, 1).replace(/\n /g, "\n  ") + ";\n" +
    "// Tutor moves -> species a tutor taught them in some generation, besides Gen 6's learnsets.\n" +
    "window.TUTOR_LEARNERS = " + JSON.stringify(tutors, null, 1).replace(/\n /g, "\n  ") + ";\n";
  fs.writeFileSync(path.join(root, "data/machine-learners.js"), body);
  console.log("wrote data/machine-learners.js: " + Object.entries(out).concat(Object.entries(tutors)).map(([m, l]) => m + " +" + l.length).join(", "));
})();
