// Builds data/wild-items.js: the items wild Pokémon may be holding, by
// species: FireRed's (src/data/pokemon/species_info.h, .itemCommon and
// .itemRare); for a species FireRed gives none, Emerald's (the same table,
// as Ruby and Sapphire have it); for one neither gives any, none. Only Gen 3's
// 386 have any. game/encounters.js gives them out (50% the common item, 5%
// the rare one; both the same item, always).
//
//   node tools/build-wild-items.js <path to pokefirered> <path to pokeemerald's src/data/pokemon/species_info.h>
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const [fr, em] = [process.argv[2], process.argv[3]];
const frFile = fr && path.join(fr, "src/data/pokemon/species_info.h");
if (!frFile || !fs.existsSync(frFile) || !em || !fs.existsSync(em)) {
  console.error("Usage: node tools/build-wild-items.js <path to pokefirered> <pokeemerald's src/data/pokemon/species_info.h>");
  process.exit(1);
}
global.window = global;
for (const f of ["data/dex.js", "data/items.js"]) vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));

const toID = (s) => String(s).toLowerCase().replace(/[^a-z0-9]/g, "");
const species = {};
for (const k of Object.keys(window.DEX)) if (window.DEX[k].id <= 386) species[toID(k)] = k;
const items = {};
for (const k of Object.keys(window.ITEMS)) items[toID(k)] = k;

// [SPECIES_X] = { ... .itemCommon = ITEM_A, .itemRare = ITEM_B ... } -> { Species: [common, rare] } (null: none).
const missing = new Set();
function read(file) {
  const text = fs.readFileSync(file, "utf8"), out = {};
  for (const m of text.matchAll(/\[SPECIES_(\w+)\]\s*=\s*\{([\s\S]*?)\n\s*\},/g)) {
    const name = species[toID(m[1])];
    if (!name) continue;
    const item = (field) => {
      const v = (new RegExp("\\." + field + "\\s*=\\s*ITEM_(\\w+)").exec(m[2]) || [])[1];
      if (!v || v === "NONE") return null;
      const id = items[toID(v)];
      if (!id) missing.add(v);
      return id || null;
    };
    const pair = [item("itemCommon"), item("itemRare")];
    if (pair[0] || pair[1]) out[name] = pair;
  }
  return out;
}
const fromFr = read(frFile), fromEm = read(em);
const out = {};
let frCount = 0, emCount = 0;
for (const name of Object.keys(window.DEX).filter((k) => window.DEX[k].id <= 386).sort((a, b) => window.DEX[a].id - window.DEX[b].id)) {
  if (fromFr[name]) { out[name] = fromFr[name]; frCount++; }
  else if (fromEm[name]) { out[name] = fromEm[name]; emCount++; }
}
fs.writeFileSync(path.join(root, "data/wild-items.js"),
  "// Auto-generated by tools/build-wild-items.js. Do not edit by hand.\n" +
  "// Items wild Pokémon may hold: [common (50%), rare (5%)], null for none; FireRed's, else Emerald's.\n" +
  "window.WILD_ITEMS = " + JSON.stringify(out) + ";\n");
console.log("wrote data/wild-items.js: " + frCount + " species from FireRed, " + emCount + " from Emerald" +
  (missing.size ? "; no item here for " + [...missing].join(", ") : ""));
