// Hoenn's shop lists, from a pret/pokeemerald checkout: node tools/build-hoenn-marts.js <path to pokeemerald>
//
// A shop's stock is a label of .2byte lines closed by the pokemartlistend macro. tools/lib/emerald-script.js reads
// such a label as a script (the macro is not a .2byte), which drops the stock, so every Hoenn Poké Mart and
// decoration counter came out empty. This writes the lists themselves to data/hoenn-marts.js, which adds them to
// HOENN_SCRIPTS.tb where ui/hoenn-script.js's pokemart and pokemartdecoration look for them.
"use strict";
const fs = require("fs"), path = require("path");
const EM = process.argv[2] || process.env.POKEEMERALD;
if (!EM || !fs.existsSync(path.join(EM, "data/maps"))) { console.error("Usage: node tools/build-hoenn-marts.js <path to pret/pokeemerald>"); process.exit(1); }
const lists = {};
const files = fs.readdirSync(path.join(EM, "data/maps")).map((d) => path.join(EM, "data/maps", d, "scripts.inc")).concat(fs.readdirSync(path.join(EM, "data/scripts")).map((f) => path.join(EM, "data/scripts", f)));
for (const file of files) {
  if (!fs.existsSync(file) || !file.endsWith(".inc")) continue;
  let label = null, rows = [];
  for (const raw of fs.readFileSync(file, "utf8").split("\n")) {
    const line = raw.replace(/@.*$/, "").trim();
    const l = /^(\w+)::?$/.exec(line);
    if (l) { label = l[1]; rows = []; continue; }
    const w = /^\.2byte\s+((?:ITEM|DECOR)_\w+)$/.exec(line);
    if (w) { rows.push([w[1]]); continue; }
    // (The rooftop sale's list closes with a bare ".2byte 0".)
    if ((line === "pokemartlistend" || /^\.2byte\s+0$/.test(line)) && label && rows.length && /Pokemart/.test(label)) { lists[label] = rows.filter((r) => r[0] !== "ITEM_NONE"); rows = []; continue; }
    if (line && !line.startsWith(".")) rows = [];
  }
}
const out = "// Generated by tools/build-hoenn-marts.js from pret/pokeemerald: each shop's stock (data/maps/*/scripts.inc).\n" +
  "Object.assign(window.HOENN_SCRIPTS.tb, " + JSON.stringify(lists) + ");\n";
fs.writeFileSync(path.join(__dirname, "../data/hoenn-marts.js"), out);
console.log(Object.keys(lists).length + " shop lists, " + Object.values(lists).reduce((n, l) => n + l.length, 0) + " entries");
