// Max Moves and G-Max Moves (Sword and Shield), from @pkmn/dex (Pokémon
// Showdown's data, Gen 8):
//
//   node tools/build-max-moves.js
//
// Writes data/max-moves.js: the 18 Max Moves, Max Guard and the 33 G-Max
// Moves added to window.MOVES (gen 8, isMax), and window.MAX_MOVES:
//   power:  { move: the power of the Max Move it becomes } for every damaging
//           move here (Showdown's table: by the move's power, lower for
//           Fighting and Poison moves)
//   byType: { type: its Max Move } (Max Flare, Max Geyser, ...)
//   gmax:   { species: its G-Max Move } for the Pokémon that can Gigantamax
//           (its Gigantamax forme is "<species>-Gmax", data/dex-forms.js)
// Their effects (weather, terrain, stat changes, the G-Max Moves' own) are in
// data/battle-moves.js.
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { Dex } = require("@pkmn/dex");

const root = path.join(__dirname, "..");
global.window = global;
for (const f of ["data/moves.js", "data/moves-gen7.js", "data/moves-gen8.js"]) vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));
const gen8 = Dex.forGen(8);

const moves = {}, power = {}, byType = {}, gmax = {};
for (const m of gen8.moves.all()) {
  if (!m.isMax) continue;
  const out = { power: m.basePower >= 160 ? m.basePower : 0, acc: null, cat: m.category, type: m.type, pp: 1, priority: m.priority,
    target: m.target, flags: Object.assign({}, m.flags), isMax: true, gen: 8 };
  if (m.ignoreAbility) out.ignoreAbility = true;
  if (m.id === "maxguard") out.volatileStatus = "maxguard";
  out.desc = m.desc; out.shortDesc = m.shortDesc;
  moves[m.name] = out;
  if (m.isMax === true && m.category !== "Status") byType[m.type] = m.name;
}
for (const s of gen8.species.all()) {
  if (s.canGigantamax && !s.isNonstandard) gmax[s.name.replace(/’/g, "'")] = s.canGigantamax;
}
for (const name of Object.keys(window.MOVES)) {
  const m = Dex.moves.get(name);
  if (m.exists && m.maxMove && m.maxMove.basePower) power[name] = m.maxMove.basePower;
}
const ser = (o) => "{\n" + Object.entries(o).map(([k, v]) => "  " + JSON.stringify(k) + ": " + JSON.stringify(v)).join(",\n") + "\n}";
fs.writeFileSync(path.join(root, "data/max-moves.js"),
  "// Auto-generated by tools/build-max-moves.js from @pkmn/dex (Gen 8). Do not edit by hand.\n" +
  "// The Max Moves and G-Max Moves, added to window.MOVES, and what Dynamax makes of each move.\n" +
  "Object.assign(window.MOVES, " + ser(moves) + ");\n" +
  "window.MAX_MOVES = " + JSON.stringify({ power, byType, gmax }) + ";\n");
console.log("wrote data/max-moves.js: " + Object.keys(moves).length + " Max Moves, " + Object.keys(power).length + " powers, " +
  Object.keys(gmax).length + " Gigantamax species");
