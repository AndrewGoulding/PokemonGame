// Builds FireRed's party screen (the POKéMON menu) from pret/pokefirered,
// and the party icons:
//
//   node tools/build-party-menu.js <path to pokefirered> <path to pokeemerald-expansion>
//   (or set POKEFIRERED and POKEEMERALD_EXPANSION)
//
// Writes data/party-menu.js: window.PARTY_MENU = {
//   tiles:    graphics/party_menu/bg.png, 64x64 (8x8 tiles, 8 to a row): one hex
//             digit a pixel, the colour number (0-15) in the tile's palette
//   palette:  bg.pal's 176 colours (11 palettes): the party menu's palette
//             buffer, which the slots' colours are picked from by number
//   bg:       bg.bin, BG1 (the background and the CANCEL button): 32x20 tile
//             entries (tile | hflip 0x400 | vflip 0x800 | palette << 12)
//   slots:    the slot pictures, as tile numbers into `tiles` (src/data/party_menu.h):
//             main (10x7, the first Pokémon's), mainNoHp, wide (18x3, the
//             others), wideNoHp, wideEmpty
//   buttons:  confirm_button.bin and cancel_button.bin, 7x2 BG1 tile entries each:
//             CONFIRM and CANCEL when choosing several Pokémon (DrawCancelConfirmButtons)
//   pokeball, pokeballSmall, hold, status: sprite sheets ({ width, height, px, palette })
//             from graphics/party_menu/ and graphics/interface/status_icons.png
// }
// and assets/sprites/icons/<dex id>[-<form>].png: each Pokémon's party icon,
// two 32x32 frames one above the other, as the game's sprites are named.
// FireRed's own icons for the first 386 (graphics/pokemon/*/icon.png, in
// their icon palette); later Pokémon and alternate forms (Megas, Rotom's
// appliances, ...) from pokeemerald-expansion, which carries them in the same
// style.
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { readPng, writePng, readPal } = require("./lib/png");

const pret = process.argv[2] || process.env.POKEFIRERED;
const expansion = process.argv[3] || process.env.POKEEMERALD_EXPANSION;
const P = (...p) => path.join(pret || "", ...p);
const X = (...p) => path.join(expansion || "", ...p);
if (!pret || !fs.existsSync(P("graphics/party_menu/bg.bin")) || !fs.existsSync(P("src/pokemon_icon.c")) ||
    !expansion || !fs.existsSync(X("src/data/graphics/pokemon.h"))) {
  console.error("Usage: node tools/build-party-menu.js <path to pret/pokefirered> <path to pokeemerald-expansion>\n" +
    "(needs graphics/party_menu/, graphics/interface/status_icons.png, graphics/pokemon/*/icon.png,\n" +
    " graphics/pokemon/icon_palettes/, src/pokemon_icon.c; and the expansion's graphics/pokemon/**/icon.png,\n" +
    " graphics/pokemon/icon_palettes/, src/data/graphics/pokemon.h, src/data/pokemon/species_info/)");
  process.exit(1);
}
const root = path.join(__dirname, "..");

// ---------- The party menu's graphics ----------

const hex = (arr) => Array.from(arr, (v) => (v & 15).toString(16)).join("");
const bgPng = readPng(P("graphics/party_menu/bg.png"));
const bgMap = fs.readFileSync(P("graphics/party_menu/bg.bin"));
const bg = [];
for (let y = 0; y < 20; y++) for (let x = 0; x < 32; x++) bg.push(bgMap.readUInt16LE((y * 32 + x) * 2));
const bytes = (f) => Array.from(fs.readFileSync(P("graphics/party_menu", f)));
const sheet = (file) => {
  const img = readPng(file);
  return { width: img.width, height: img.height, px: hex(img.px), palette: img.palette.slice(0, 16) };
};
const data = {
  tiles: hex(bgPng.px),
  palette: bgPng.palette.slice(0, 176),
  bg,
  slots: {
    main: bytes("slot_main.bin"), mainNoHp: bytes("slot_main_no_hp.bin"),
    wide: bytes("slot_wide.bin"), wideNoHp: bytes("slot_wide_no_hp.bin"), wideEmpty: bytes("slot_wide_empty.bin")
  },
  buttons: Object.fromEntries(["confirm", "cancel"].map((n) => {
    const b = fs.readFileSync(P("graphics/party_menu", n + "_button.bin"));
    return [n, Array.from({ length: 14 }, (_, i) => b.readUInt16LE(i * 2))];
  })),
  pokeball: sheet(P("graphics/party_menu/pokeball.png")),
  pokeballSmall: sheet(P("graphics/party_menu/pokeball_small.png")),
  hold: sheet(P("graphics/party_menu/hold_icons.png")),
  status: sheet(P("graphics/interface/status_icons.png"))
};
fs.writeFileSync(path.join(root, "data/party-menu.js"),
  "// Auto-generated by tools/build-party-menu.js from pret/pokefirered. Do not edit by hand.\n" +
  "window.PARTY_MENU = " + JSON.stringify(data) + ";\n");

// ---------- Party icons ----------

global.window = global;
vm.runInThisContext(fs.readFileSync(path.join(root, "data/dex.js"), "utf8"));
window.LEARNSETS_GEN6 = {};
for (const f of ["data/dex-gen7.js", "data/dex-gen8.js", "data/dex-forms.js"]) vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));

// "Mr. Mime" -> MR_MIME, "Nidoran-F" -> NIDORAN_F, "Charizard-Mega-X" -> CHARIZARD_MEGA_X.
const constName = (name) => name.toUpperCase().replace(/É/g, "E").replace(/['.:]/g, "")
  .replace(/[^A-Z0-9]+/g, "_").replace(/^_|_$/g, "");

// FireRed: SPECIES_X -> icon palette, and the folder (graphics/pokemon/x/icon.png).
const iconC = fs.readFileSync(P("src/pokemon_icon.c"), "utf8");
const frPal = {};
const palBody = iconC.slice(iconC.indexOf("gMonIconPaletteIndices[]"));
for (const [, s, n] of palBody.slice(0, palBody.indexOf("};")).matchAll(/\[SPECIES_(\w+)\]\s*=\s*(\d+)/g)) frPal[s] = +n;
const frPals = [0, 1, 2].map((i) => readPal(P("graphics/pokemon/icon_palettes/icon_palette_" + i + ".pal")));

// The expansion: SPECIES_X -> { icon path, palette }, in file order (a
// species' first form is its usual one: DEOXYS_NORMAL, WORMADAM_PLANT).
const gfx = {};
for (const [, name, file] of fs.readFileSync(X("src/data/graphics/pokemon.h"), "utf8")
  .matchAll(/const u8 (gMonIcon_\w+)\[\] = INCGFX_U8\("([^"]+)"/g)) if (!(name in gfx) && !/_gba\.png$/.test(file)) gfx[name] = file;
const xSpecies = [];
for (const f of fs.readdirSync(X("src/data/pokemon/species_info")).filter((f) => /^gen_\d_families\.h$/.test(f)).sort()) {
  const src = fs.readFileSync(X("src/data/pokemon/species_info", f), "utf8");
  for (const block of src.split(/\n    \[SPECIES_/).slice(1)) {
    const id = /^(\w+)\]/.exec(block)[1];
    const sprite = /\.iconSprite = (gMonIcon_\w+)/.exec(block), pal = /\.iconPalIndex = (\d+)/.exec(block);
    if (sprite && pal && gfx[sprite[1]]) xSpecies.push({ id, file: gfx[sprite[1]], pal: +pal[1] });
  }
}
const xPals = [0, 1, 2, 3, 4, 5].map((i) => readPal(X("graphics/pokemon/icon_palettes/pal" + i + ".pal")));
const xFind = (c) => xSpecies.find((s) => s.id === c) || xSpecies.find((s) => s.id.startsWith(c + "_"));

function writeIcon(file, out, colours) {
  const img = readPng(file);
  const rgba = new Uint8ClampedArray(32 * 64 * 4);
  for (let y = 0; y < Math.min(64, img.height); y++) for (let x = 0; x < 32; x++) {
    const v = img.px[y * img.width + x] & 15;
    if (!v) continue;
    const c = colours[v];
    rgba.set([c[0], c[1], c[2], 255], (y * 32 + x) * 4);
  }
  writePng(out, 32, 64, rgba);
}

// Names the expansion files differently.
const ICON_FOLDERS = { MINIOR_CORE: "minior/core/red", GRENINJA_BOND: "greninja", ZYGARDE_10: "zygarde/10_percent" };
const outDir = path.join(root, "assets/sprites/icons");
fs.mkdirSync(outDir, { recursive: true });
let fromFr = 0, fromX = 0;
const missing = [];
// (Alcremie itself is the expansion's vanilla cream with a Strawberry Sweet,
// not the first ALCREMIE_ it lists, the Gigantamax.)
const SPECIES_CONST = { ALCREMIE: "ALCREMIE_STRAWBERRY_VANILLA_CREAM" };
const want = Object.entries(window.DEX).map(([name, d]) => ({ name, id: d.id, c: SPECIES_CONST[constName(name)] || constName(name) }));
// Burmy's cloaks (Party.form) have their own icons too.
want.push({ name: "Burmy (Sandy Cloak)", id: "412-sandy", c: "BURMY_SANDY" }, { name: "Burmy (Trash Cloak)", id: "412-trash", c: "BURMY_TRASH" });
// And Alcremie's looks: "ruby-cream-strawberry-sweet" is the expansion's ALCREMIE_STRAWBERRY_RUBY_CREAM.
for (const f of window.ALCREMIE_FORMS) {
  const m = /^(.+)-(\w+)-sweet$/.exec(f);
  if (f !== "vanilla-cream-strawberry-sweet") want.push({ name: "Alcremie (" + f + ")", id: "869-" + f, c: "ALCREMIE_" + m[2].toUpperCase() + "_" + m[1].toUpperCase().replace(/-/g, "_") });
}
for (const w of want) {
  const out = path.join(outDir, w.id + ".png");
  const base = w.c.split("_")[0];
  const frC = w.c in frPal ? w.c : base in frPal && typeof w.id === "number" && w.id <= 386 && /_(NORMAL|F|M)$|^[A-Z0-9]+$/.test(w.c) ? base : null;
  const frFolder = frC && [frC.toLowerCase(), frC.toLowerCase() + "/a"].map((d) => P("graphics/pokemon", d, "icon.png")).find(fs.existsSync);
  if (typeof w.id === "number" && w.id <= 386 && frFolder) {
    writeIcon(frFolder, out, frPals[frPal[frC]]);
    fromFr++;
    continue;
  }
  const x = xFind(w.c);
  if (x && fs.existsSync(X(x.file))) { writeIcon(X(x.file), out, xPals[x.pal]); fromX++; continue; }
  // (Species written with macros, like Arceus's types: their folder's
  // icon.png, which carries its own palette.)
  // (Or a form's folder under its species', "minior/core/red"; or, for a
  // form without one, its species' own icon: Silvally's types share one.)
  const folders = [w.c.toLowerCase(), ICON_FOLDERS[w.c], w.c.toLowerCase().replace("_", "/"), base.toLowerCase()].filter(Boolean)
    .map((d) => X("graphics/pokemon", d, "icon.png"));
  const folder = folders.find(fs.existsSync);
  if (folder) { writeIcon(folder, out, readPng(folder).palette); fromX++; continue; }
  missing.push(w.name);
}
console.log("wrote data/party-menu.js and assets/sprites/icons/: " + fromFr + " FireRed icons, " + fromX + " from the expansion" +
  (missing.length ? "; no icon for " + missing.join(", ") : ""));
