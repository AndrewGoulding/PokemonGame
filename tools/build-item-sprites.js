// Builds data/item-sprites.js: item id -> sprite path under assets/sprites/items/,
// and where in each picture the item is (ITEM_SPRITE_BOXES).
// Run with: npm run build:item-sprites (after adding item sprites)
//
// Sprites live in category folders, and some folders drop the suffix their
// items share: ball/great.png is great-ball, berry/oran.png is oran-berry.
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const spriteDir = path.join(root, "assets/sprites/items");
global.window = global;
for (const f of ["data/items.js", "data/moves.js", "data/natures.js"]) {
  vm.runInThisContext(fs.readFileSync(path.join(root, f), "utf8"));
}

// TMs and HMs use a disc coloured by the move's type: tm/fire.png, hm/water.png.
function machineSprite(id) {
  const m = /^(tm|hm)\d+$/.exec(id);
  const move = m && /^Teaches (.+?) to a compatible/.exec(window.ITEMS[id].effect || "");
  if (!move || !window.MOVES[move[1]]) return null;
  const file = m[1] + "/" + window.MOVES[move[1]].type.toLowerCase();
  return exists(file.split("/")[0], file.split("/")[1]) ? file : null;
}

// Mints are coloured by the stat their nature raises: mint/attack.png, mint/neutral.png.
const STAT_FILES = { atk: "attack", def: "defense", spa: "special-attack", spd: "special-defense", spe: "speed" };
function mintSprite(id) {
  const m = /^([a-z]+)-mint$/.exec(id);
  const nature = m && window.NATURES[m[1].charAt(0).toUpperCase() + m[1].slice(1)];
  if (!nature) return null;
  const file = STAT_FILES[nature.plus] || "neutral";
  return exists("mint", file) ? "mint/" + file : null;
}

// Folder -> the suffix its file names leave out.
const SUFFIX_FOLDERS = {
  ball: "-ball", berry: "-berry", gem: "-gem", fossil: "-fossil", flute: "-flute",
  shard: "-shard", plate: "-plate", incense: "-incense", memory: "-memory"
};

const exists = (folder, name) => fs.existsSync(path.join(spriteDir, folder, name + ".png"));
const folders = fs.readdirSync(spriteDir).filter((d) => fs.statSync(path.join(spriteDir, d)).isDirectory());

// Items whose sprite file has a different name.
const ALIASES = { "town-map": "key-item/town-map-gen3", "old-amber": "fossil/old-amber" };

const out = {};
for (const id of Object.keys(window.ITEMS).sort()) {
  let found = machineSprite(id) || mintSprite(id) || ALIASES[id];
  for (const [folder, suffix] of Object.entries(SUFFIX_FOLDERS)) {
    if (!found && id.endsWith(suffix) && exists(folder, id.slice(0, -suffix.length))) {
      found = folder + "/" + id.slice(0, -suffix.length);
      break;
    }
  }
  if (!found) {
    const folder = folders.find((f) => !SUFFIX_FOLDERS[f] && exists(f, id));
    if (folder) found = folder + "/" + id;
  }
  if (found) out[id] = "assets/sprites/items/" + found + ".png";
}

// Where each picture's visible pixels are, [x, y, width, height, image width,
// image height], so a picture can be shown cropped to the item (the digging
// game stretches treasures over their shapes).
const { readPng } = require("./lib/png");
const boxes = {};
for (const [id, file] of Object.entries(out)) {
  let png;
  try { png = readPng(path.join(root, file)); } catch (e) { continue; }   // (a few use PNG formats tools/lib/png.js doesn't read)
  let x0 = png.width, y0 = png.height, x1 = -1, y1 = -1;
  for (let y = 0; y < png.height; y++) for (let x = 0; x < png.width; x++) {
    if (!png.px[y * png.width + x]) continue;
    x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
  }
  if (x1 >= 0) boxes[id] = [x0, y0, x1 - x0 + 1, y1 - y0 + 1, png.width, png.height];
}

const body = "// Auto-generated by tools/build-item-sprites.js. Do not edit by hand.\n" +
  "window.ITEM_SPRITES = " + JSON.stringify(out, null, 1).replace(/\n /g, "\n  ") + ";\n" +
  "// [x, y, width, height, image width, image height] of each picture's visible pixels.\n" +
  "window.ITEM_SPRITE_BOXES = " + JSON.stringify(boxes) + ";\n";
fs.writeFileSync(path.join(root, "data/item-sprites.js"), body);
console.log("wrote data/item-sprites.js: " + Object.keys(out).length + " of " +
  Object.keys(window.ITEMS).length + " items have sprites");
