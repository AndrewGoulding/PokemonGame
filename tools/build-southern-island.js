// Builds Southern Island (Emerald's SouthernIsland_Exterior and _Interior) from
// a pret/pokeemerald checkout, in this game's map format, into
// data/southern-island.js (loaded after data/emerald-maps.js, whose Hoenn build
// leaves it out). Its people and the Lati's scene are this game's own
// (ui/game.js's southernIsland*): the S.S. Tidal's sailor on the shore, and
// inside, at the stone, Latias or Latios (Omega Ruby and Alpha Sapphire's
// favourite-colour gift; the other one after the Hall of Fame).
//
//   node tools/build-southern-island.js <path to pret/pokeemerald>
//
// Writes:
//   assets/world/maps/SouthernIsland_Exterior*.png, SouthernIsland_Interior*.png
//   data/southern-island.js
"use strict";
const fs = require("fs");
const path = require("path");
const { writePng } = require("./lib/png");
const EM = process.argv[2] || process.env.POKEEMERALD;
if (!EM || !fs.existsSync(path.join(EM, "data/maps/SouthernIsland_Interior/map.json"))) {
  console.error("Usage: node tools/build-southern-island.js <path to pret/pokeemerald>");
  process.exit(1);
}
const root = path.join(__dirname, "..");
const P = (...p) => path.join(EM, ...p);
const outMaps = path.join(root, "assets/world/maps");
const { GENERAL_ANIMS, loadTileset, metatile, render, animCells, writeAnimSheet, frBehavior, tilesetFolder } = require("./lib/emerald-tiles")(EM);

const layouts = {};
for (const l of JSON.parse(fs.readFileSync(P("data/layouts/layouts.json"), "utf8")).layouts) if (l.id) layouts[l.id] = l;
const general = loadTileset("primary", "general", GENERAL_ANIMS);
const NAMES = { MAP_SOUTHERN_ISLAND_EXTERIOR: "SouthernIsland_Exterior", MAP_SOUTHERN_ISLAND_INTERIOR: "SouthernIsland_Interior",
  MAP_LILYCOVE_CITY_HARBOR: "LilycoveCity_Harbor" };
const person = (id, localId, x, y, sprite, w, h, frames, movement, script, extra) => Object.assign(
  { id, localId, x, y, movement, rangeX: 0, rangeY: 0, script, flag: null, text: null, sprite, width: w, height: h, frames }, extra || {});
const PEOPLE = {
  SouthernIsland_Exterior: [
    person(0, "LOCALID_SOUTHERN_ISLAND_SAILOR", 13, 23, "em_sailor", 16, 32, 9, "face_up", "SouthernIsland_Exterior_EventScript_Sailor"),
    person(1, "LOCALID_SOUTHERN_ISLAND_SS_TIDAL", 13, 25, "em_misc_ss_tidal", 96, 40, 1, "face_right", "0x0", { inanimate: true })
  ],
  // (The Lati, hidden till its scene: ui/game.js adds it, Latias or Latios.)
  SouthernIsland_Interior: []
};
const out = {};
for (const name of ["SouthernIsland_Exterior", "SouthernIsland_Interior"]) {
  const map = JSON.parse(fs.readFileSync(P("data/maps", name, "map.json"), "utf8"));
  const layout = layouts[map.layout];
  const w = layout.width, h = layout.height;
  const secondary = loadTileset("secondary", tilesetFolder(layout.secondary_tileset));
  const bin = fs.readFileSync(P(layout.blockdata_filepath));
  const blocks = Array.from({ length: w * h }, (_, i) => bin.readUInt16LE(i * 2));
  const r = render(blocks, w, h, general, secondary, false);
  writePng(path.join(outMaps, name + ".png"), w * 16, h * 16, r.below);
  if (r.anyAbove) writePng(path.join(outMaps, name + "-top.png"), w * 16, h * 16, r.above);
  const bb = fs.readFileSync(P(layout.border_filepath));
  writePng(path.join(outMaps, name + "-border.png"), 32, 32, render([0, 1, 2, 3].map((i) => bb.readUInt16LE(i * 2)), 2, 2, general, secondary, true).below);
  const anim = animCells(blocks, w, h, general, secondary);
  if (anim.pics.length) writeAnimSheet(path.join(outMaps, name + "-anim.png"), anim.pics);
  const collision = [], elevation = [], behavior = [], encounter = [];
  for (const b of blocks) {
    const mt = metatile(general, secondary, b & 0x3ff);
    collision.push((b >> 10) & 3); elevation.push(b >> 12); behavior.push(frBehavior(mt.behavior)); encounter.push(0);
  }
  out[name] = {
    name, title: "Southern Island", width: w, height: h, type: "route", music: "em_abandoned_ship", region: "hoenn",
    cycling: !!map.allow_cycling, showName: true, top: r.anyAbove, borderWidth: 2, borderHeight: 2,
    anim: anim.cells.length ? { cells: anim.cells, anims: general.anims.map((a) => a.name) } : undefined,
    collision, elevation, behavior, encounter, connections: [],
    warps: map.warp_events.map((wp) => ({ x: wp.x, y: wp.y, map: NAMES[wp.dest_map], warp: +wp.dest_warp_id })),
    // (Its signs' words are Emerald's, data/emerald-maps.js's texts: the stone inside is the Lati's scene.)
    signs: (map.bg_events || []).map((b) => ({ x: b.x, y: b.y, script: b.script === "SouthernIsland_Interior_EventScript_TryLatiEncounter"
      ? "SouthernIsland_Interior_EventScript_Stone" : b.script, text: null })),
    triggers: [], hidden: [], people: PEOPLE[name], wild: null
  };
  console.log(name, w + "x" + h);
}
fs.writeFileSync(path.join(root, "data/southern-island.js"),
  "// Auto-generated by tools/build-southern-island.js from pret/pokeemerald. Do not edit by hand.\n" +
  "// Southern Island (Emerald's), which the Hoenn build (tools/build-hoenn.js) leaves out.\n" +
  "Object.assign(window.WORLD_MAPS, " + JSON.stringify(out) + ");\n" +
  "if (window.HOENN_SCRIPTS) Object.assign(window.HOENN_SCRIPTS.consts, " + JSON.stringify({ MAP_SOUTHERN_ISLAND_EXTERIOR: "SouthernIsland_Exterior", MAP_SOUTHERN_ISLAND_INTERIOR: "SouthernIsland_Interior" }) + ");\n" +
  "if (window.HOENN_TOWN_MAP) { window.HOENN_TOWN_MAP.mapSections.SouthernIsland_Exterior = \"SOUTHERN_ISLAND\"; window.HOENN_TOWN_MAP.mapSections.SouthernIsland_Interior = \"SOUTHERN_ISLAND\"; }\n");
console.log("wrote data/southern-island.js");
